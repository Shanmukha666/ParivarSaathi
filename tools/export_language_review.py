#!/usr/bin/env python3
"""Build docs/LANGUAGE_REVIEW.md: one sheet a native speaker can mark up and sign.

    python tools/export_language_review.py

Reads the REAL source (crisis phrases and replies in safety.ts, UI strings in locales/*.json), so the
sheet can never drift from what the app ships. Re-run after any text change; commit the result.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SAFETY = (ROOT / "apps/web/src/lib/safety.ts").read_text(encoding="utf-8")
LOCALES = {c: json.loads((ROOT / f"apps/web/src/locales/{c}.json").read_text(encoding="utf-8")) for c in ("en", "te", "hi", "ta")}
NAMES = {"te": "Telugu", "hi": "Hindi", "ta": "Tamil"}


def flatten(d, prefix=""):
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            yield from flatten(v, key + ".")
        else:
            yield key, str(v)


def phrases(lang):
    block = re.search(rf"\n  {lang}: \[(.*?)\n  \],", SAFETY, re.S)
    return re.findall(r"'([^']+)'", block.group(1)) if block else []


def reply(lang):
    m = re.search(rf"if \(lang === '{lang}'\) {{\s*return `(.*?)`;", SAFETY, re.S)
    return m.group(1) if m else ""


out = ["# Language review sheet", "",
       "Generated by `tools/export_language_review.py` from the shipped source. **Nothing here has had native-speaker review.**",
       "Reviewer: mark each row OK / FIX, write the correction in the last column, then sign at the bottom.", "",
       "## 1. Crisis reply (highest priority)", "",
       "Shown when a user may be at risk of self-harm. `${short}` is 14416 and `${tollFree}` is 1800-891-4416 (Tele-MANAS).",
       "A reviewer should check: is it gentle, is it natural spoken language, does it claim only what is true (free, 24 hours, own language, counsellor notified)?", ""]
for lang, name in NAMES.items():
    out += [f"### {name}", "", f"> {reply(lang)}", "", "| Verdict (OK/FIX) | Correction |", "|---|---|", "| | |", ""]

out += ["## 2. Distress phrases that trigger the crisis reply", "",
        "A missed phrase means a person in distress gets a normal answer. Please ADD colloquial, indirect and dialect expressions (for example: wishing to disappear, being a burden, 'what is the point'), and flag any phrase that is a false alarm.", ""]
for lang, name in NAMES.items():
    out += [f"### {name} ({len(phrases(lang))} phrases)", ""] + [f"- {p}" for p in phrases(lang)] + ["", "Phrases to add: ", ""]

out += ["## 3. Interface strings", "", "| Key | English | Translation | OK/FIX | Correction |", "|---|---|---|---|---|"]
en = dict(flatten(LOCALES["en"]))
for lang, name in NAMES.items():
    out.insert(len(out) - 0, "")
    tr = dict(flatten(LOCALES[lang]))
    out += ["", f"### {name}: {len(tr)} strings, {len([k for k in en if k not in tr])} missing vs English", "",
            "| Key | English | " + name + " | OK/FIX | Correction |", "|---|---|---|---|---|"]
    for k, v in tr.items():
        out.append(f"| `{k}` | {en.get(k, '').replace('|', '/')} | {v.replace('|', '/')} | | |")

out += ["", "## Sign-off", "", "| Language | Reviewer name | Qualification / native language | Date | Signature |", "|---|---|---|---|---|"]
out += [f"| {n} | | | | |" for n in NAMES.values()]
(ROOT / "docs/LANGUAGE_REVIEW.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote docs/LANGUAGE_REVIEW.md:", {c: len(phrases(c)) for c in NAMES}, "phrases;", {c: bool(reply(c)) for c in NAMES}, "replies found")
